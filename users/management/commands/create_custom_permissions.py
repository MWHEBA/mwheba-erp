"""
أمر Django لإنشاء صلاحيات مخصصة مبسطة
بدلاً من استخدام 544 صلاحية Django الافتراضية
"""
from django.core.management.base import BaseCommand
from django.contrib.auth.models import Permission
from django.contrib.contenttypes.models import ContentType
from django.contrib.contenttypes.models import ContentType as CT


class Command(BaseCommand):
    help = "إنشاء صلاحيات مخصصة مبسطة"

    def handle(self, *args, **options):
        import sys
        if hasattr(sys.stdout, 'reconfigure'):
            sys.stdout.reconfigure(encoding='utf-8')
        self.stdout.write(self.style.SUCCESS("بدء إنشاء الصلاحيات المخصصة..."))

        # الحصول على ContentType عام (نستخدم User كمرجع)
        from users.models import User
        content_type = ContentType.objects.get_for_model(User)

        # تعريف الصلاحيات المخصصة المبسطة (بالعربي)
        custom_permissions = [
            # ==================== المبيعات ====================
            ('ادارة_المبيعات', 'إدارة المبيعات', 'إنشاء وتعديل فواتير المبيعات'),
            ('عرض_المبيعات', 'عرض المبيعات', 'عرض فواتير المبيعات فقط'),
            ('ادارة_مرتجعات_المبيعات', 'إدارة مرتجعات المبيعات', 'إنشاء وتعديل مرتجعات البيع'),
            ('تغيير_مسؤول_المبيعات', 'تغيير مسؤول المبيعات', 'إمكانية اختيار أو تغيير مسؤول المبيعات في الفواتير وعروض الأسعار'),
            ('ادارة_الحقول_الاضافية', 'إدارة الحقول الإضافية', 'إدارة وتعديل تعاريف الحقول الإضافية المخصصة في المبيعات وعروض الأسعار'),
            
            # ==================== المشتريات ====================
            ('ادارة_المشتريات', 'إدارة المشتريات', 'إنشاء وتعديل فواتير المشتريات'),
            ('عرض_المشتريات', 'عرض المشتريات', 'عرض فواتير المشتريات فقط'),
            ('ادارة_مرتجعات_المشتريات', 'إدارة مرتجعات المشتريات', 'إنشاء وتعديل مرتجعات الشراء'),
            
            # ==================== العملاء ====================
            ('ادارة_العملاء', 'إدارة العملاء', 'إضافة وتعديل بيانات العملاء'),
            ('عرض_العملاء', 'عرض العملاء', 'عرض بيانات العملاء فقط'),
            ('ادارة_مدفوعات_العملاء', 'إدارة مدفوعات العملاء', 'تسجيل وإدارة مدفوعات العملاء'),
            
            # ==================== الموردين ====================
            ('ادارة_الموردين', 'إدارة الموردين', 'إضافة وتعديل بيانات الموردين'),
            ('عرض_الموردين', 'عرض الموردين', 'عرض بيانات الموردين فقط'),
            ('ادارة_مدفوعات_الموردين', 'إدارة مدفوعات الموردين', 'تسجيل وإدارة مدفوعات الموردين'),
            
            # ==================== المنتجات والمخزون ====================
            ('ادارة_المنتجات', 'إدارة المنتجات', 'إضافة وتعديل المنتجات والتصنيفات'),
            ('عرض_المنتجات', 'عرض المنتجات', 'عرض المنتجات والمخزون فقط'),
            ('ادارة_المخزون', 'إدارة المخزون', 'إدارة حركات المخزون والجرد'),
            ('ادارة_المخازن', 'إدارة المخازن', 'إضافة وتعديل المخازن'),
            
            # ==================== المالية والمحاسبة ====================
            ('ادارة_المحاسبة', 'إدارة المحاسبة', 'إنشاء وتعديل القيود المحاسبية'),
            ('عرض_المحاسبة', 'عرض المحاسبة', 'عرض القيود والحسابات فقط'),
            ('ادارة_المصروفات', 'إدارة المصروفات', 'تسجيل وإدارة المصروفات'),
            ('ادارة_الايرادات', 'إدارة الإيرادات', 'تسجيل وإدارة الإيرادات'),
            ('ادارة_الخزن_والحسابات', 'إدارة الخزن والحسابات', 'إدارة الخزن والحسابات البنكية'),
            ('عرض_التقارير_المالية', 'عرض التقارير المالية', 'عرض جميع التقارير المالية'),
            ('ادارة_الفترات_المحاسبية', 'إدارة الفترات المحاسبية', 'فتح وإغلاق الفترات المحاسبية'),
            
            # ==================== التقارير ====================
            ('عرض_تقارير_المبيعات', 'عرض تقارير المبيعات', 'عرض تقارير المبيعات التفصيلية'),
            ('عرض_تقارير_المشتريات', 'عرض تقارير المشتريات', 'عرض تقارير المشتريات التفصيلية'),
            ('عرض_تقارير_المخزون', 'عرض تقارير المخزون', 'عرض تقارير المخزون والحركات'),
            ('عرض_تقارير_العملاء', 'عرض تقارير العملاء', 'عرض كشوف حساب العملاء'),
            ('عرض_تقارير_الموردين', 'عرض تقارير الموردين', 'عرض كشوف حساب الموردين'),
            
            # ==================== المستخدمين والصلاحيات ====================
            ('ادارة_المستخدمين', 'إدارة المستخدمين', 'إضافة وتعديل المستخدمين'),
            ('ادارة_الادوار_والصلاحيات', 'إدارة الأدوار والصلاحيات', 'إنشاء وتعديل الأدوار'),
            ('عرض_سجل_النشاطات', 'عرض سجل النشاطات', 'عرض سجل نشاطات المستخدمين'),
            
            # ==================== الإعدادات ====================
            ('ادارة_اعدادات_النظام', 'إدارة إعدادات النظام', 'تعديل إعدادات النظام العامة'),
            ('ادارة_اعدادات_الشركة', 'إدارة إعدادات الشركة', 'تعديل بيانات الشركة'),
            ('ادارة_النسخ_الاحتياطي', 'إدارة النسخ الاحتياطي', 'إنشاء واستعادة النسخ الاحتياطية'),
            ('فحص_سلامة_البيانات', 'فحص سلامة البيانات', 'فحص وإصلاح البيانات'),
            
            # ==================== التسعير والطباعة ====================
            ('ادارة_التسعير', 'إدارة التسعير', 'إدارة طلبات التسعير والطباعة'),
            ('عرض_التسعير', 'عرض التسعير', 'عرض طلبات التسعير فقط'),
            
            # ==================== الخدمات المتخصصة ====================
            ('ادارة_الخدمات_المتخصصة', 'إدارة الخدمات المتخصصة', 'إدارة الموردين والخدمات المتخصصة'),
            
            # ==================== صلاحيات خاصة ====================
            ('حذف_المعاملات', 'حذف المعاملات', 'حذف الفواتير والمعاملات المالية'),
            ('اعتماد_المعاملات', 'اعتماد المعاملات', 'اعتماد الفواتير والمعاملات'),
            ('تعديل_المعاملات_المعتمدة', 'تعديل المعاملات المعتمدة', 'تعديل المعاملات بعد اعتمادها'),
        ]

        created_count = 0
        updated_count = 0
        
        for codename, name, description in custom_permissions:
            permission, created = Permission.objects.get_or_create(
                codename=codename,
                content_type=content_type,
                defaults={
                    'name': name,
                }
            )
            
            if created:
                created_count += 1
                self.stdout.write(f"✅ تم إنشاء: {name} ({codename})")
            else:
                # تحديث الاسم إذا تغير
                if permission.name != name:
                    permission.name = name
                    permission.save()
                    updated_count += 1
                    self.stdout.write(f"⚠️  تم تحديث: {name}")

        # النتيجة النهائية
        self.stdout.write("\n" + "=" * 70)
        if created_count > 0:
            self.stdout.write(
                self.style.SUCCESS(f"🎉 تم إنشاء {created_count} صلاحية مخصصة جديدة!")
            )
        if updated_count > 0:
            self.stdout.write(
                self.style.WARNING(f"⚠️  تم تحديث {updated_count} صلاحية موجودة")
            )
        
        total_custom = Permission.objects.filter(content_type=content_type).count()
        self.stdout.write(
            self.style.SUCCESS(f"\n📊 إجمالي الصلاحيات المخصصة: {total_custom} صلاحية")
        )
        
        # مقارنة
        total_all = Permission.objects.count()
        self.stdout.write(
            self.style.WARNING(f"📊 إجمالي صلاحيات Django: {total_all} صلاحية")
        )
        
        reduction = ((total_all - total_custom) / total_all * 100) if total_all > 0 else 0
        self.stdout.write(
            self.style.SUCCESS(f"✨ تقليل بنسبة: {reduction:.1f}%")
        )
        
        self.stdout.write("\n" + "=" * 70)
        self.stdout.write(self.style.SUCCESS("💡 الخطوة التالية:"))
        self.stdout.write("   قم بتشغيل: python manage.py update_roles_with_custom_permissions")
        self.stdout.write("=" * 70)
